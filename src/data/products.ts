export const products = suppliedProducts.map(normalizeProductCopy)

export const formatPrice = (value: number) =>
  new Intl.NumberFormat('en-IN', {
    style: 'currency',
    currency: 'INR',
    maximumFractionDigits: 0,
  }).format(value)

export const formatProductPrice = (product: Product) =>
  product.price !== null ? formatPrice(product.price) : product.mrp !== null ? `MRP ${formatPrice(product.mrp)}` : 'Price on launch'

export const getProductById = (id: string) => {
  const product = products.find((item) => item.id === id)
  if (!product) throw new Error(`Unknown SkinFox product: ${id}`)
  return product
}

export const getQuizRecommendation = (concern?: string) => {
  const matches: Record<string, string[]> = {
    'Sun protection': ['rayyvia-sun-protect'],
    'Gentle moisture': ['coco-kiss-moisturizing-lotion'],
    'Face cleansing': ['acnfin-soft-face-wash'],
    Cleansing: ['onion-shampoo'],
    Oiling: ['onion-hair-oil'],
    'Scalp care': ['intensive-scalp-hair-treatment'],
    'Dry skin': ['hydrelle-dry-skin-specialist'],
  }
  const ids = matches[concern ?? ''] ?? ['rayyvia-sun-protect', 'coco-kiss-moisturizing-lotion']
  return ids.map(getProductById)
}
